<#
.SYNOPSIS
  Install (or refresh) the launcher in the llama.cpp folder so the repo is the single source of truth.
.DESCRIPTION
  Writes <llamacpp_dir>\run-llama-server.bat that calls llamacpp\run-llama-server.ps1 from this repo.
  Keeps a .bak of any existing bat. Nothing else in the llama.cpp folder is touched.
#>
param([string]$Config = (Join-Path $PSScriptRoot "..\config\local-ai.json"))
if (-not (Test-Path $Config)) { throw "Missing $Config. Copy config/local-ai.example.json to config/local-ai.json and fill it in." }
$cfg = Get-Content $Config -Raw | ConvertFrom-Json
$repo = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$bat = Join-Path $cfg.llamacpp_dir "run-llama-server.bat"
if (Test-Path $bat) { Copy-Item $bat "$bat.bak" -Force }
$pwsh = if (Get-Command pwsh -ErrorAction SilentlyContinue) { "pwsh" } else { "powershell" }
@"
@echo off
REM Generated by silver-spork\scripts\install.ps1 - edit the repo, not this file.
$pwsh -NoProfile -ExecutionPolicy Bypass -File "$repo\llamacpp\run-llama-server.ps1" %*
"@ | Set-Content $bat -Encoding ascii
Write-Host "Wrote $bat -> $repo\llamacpp\run-llama-server.ps1" -ForegroundColor Green
