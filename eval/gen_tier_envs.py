#!/usr/bin/env python3
"""Generate eval/tiers/<Tier>.env from eval/models.json (one file per tier) - `npm run eval:setup`.

    python -I eval/gen_tier_envs.py            # also copies models.example.json -> models.json when missing

Each env file is what `promptfoo eval ... --env-file eval/tiers/<Tier>.env` loads:

    PF_TIER=<Tier>              selects the provider (openai:chat:<Tier>) and the suites for its roles
    PROMPTFOO_PYTHON=<exe>      the Python promptfoo spawns for gen_tests.py / lib/*.py, from
                                PROMPTFOO_PYTHON in your environment, else config/local-ai.json
                                `python_cmd`; omitted when neither is set (promptfoo then auto-detects)

Both models.json and tiers/ are gitignored: they describe one machine. Re-run after editing
models.json or config/local-ai.json. Standard library only.
"""
from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "lib"))  # -I does not add the script directory

import toolloop  # noqa: E402

TIERS_DIR = HERE / "tiers"
HEADER = "# Generated by eval/gen_tier_envs.py from eval/models.json - edit models.json and re-run `npm run eval:setup`.\n"


def ensure_models_json(path: Path) -> bool:
    """Create models.json from the template when missing. Returns True when it was just created."""
    if path.is_file():
        return False
    shutil.copyfile(toolloop.MODELS_EXAMPLE, path)
    print(f"created {path} from {toolloop.MODELS_EXAMPLE.name}.\n"
          f"Edit it: rename the <Placeholder> tiers to your llama-server preset names, set roles, sampling and\n"
          f"thinking options as the comments describe, then run `npm run eval:setup` again.")
    return True


def write_envs(cfg: dict, out_dir: Path = TIERS_DIR) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    py = os.environ.get("PROMPTFOO_PYTHON") or toolloop.local_config().get("python_cmd") or ""
    if " " in py.strip() and not Path(py).is_file():
        print(f"warning: python_cmd {py!r} has arguments; promptfoo needs a single executable, using {py.split()[0]!r}",
              file=sys.stderr)
        py = py.split()[0]
    written = []
    for tier, m in cfg["models"].items():
        lines = [HEADER, f"PF_TIER={tier}\n"]
        if py:
            lines.append(f"PROMPTFOO_PYTHON={py}\n")
        path = out_dir / f"{tier}.env"
        path.write_text("".join(lines), encoding="utf-8")
        written.append(path)
        print(f"wrote {_show(path)}  roles={m.get('roles')}")
    stale = sorted(p for p in out_dir.glob("*.env") if p not in written)
    for p in stale:
        p.unlink()
        print(f"removed {_show(p)} (tier no longer in models.json)")
    return written


def _show(path: Path) -> str:
    try:
        return str(path.relative_to(HERE.parent))
    except ValueError:
        return str(path)


def main() -> int:
    if ensure_models_json(toolloop.MODELS_PATH):
        return 0
    try:
        cfg = toolloop.load_models()
    except toolloop.ConfigError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    written = write_envs(cfg)
    print(f"{len(written)} tier env file(s); languages={cfg.get('languages')}; server={cfg['base_url']}\n"
          f"next: npm run eval:list -- <Tier>   then   npm run eval -- --env-file eval/tiers/<Tier>.env")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
